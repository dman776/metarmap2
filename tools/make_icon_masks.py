"""
Writes src/metarmap/web/icon_masks.py: every visualizer icon (metarmap.web.icons.SHAPES) as a 20x20 alpha mask, so
the Chart can serve them (GET /api/icon/<name>) without drawing anything: a Pi has no SVG renderer, and it shouldn't
spend time on one. The Copilot fetches the masks it lacks and colors them itself.

Run it on a dev machine after changing SHAPES (or SOLID's rainbow), then commit icon_masks.py with the change:

    .venv/bin/python tools/make_icon_masks.py            # write the module
    .venv/bin/python tools/make_icon_masks.py --preview  # and print each mask as ASCII art, to eyeball them
    .venv/bin/python tools/make_icon_masks.py --check    # only say whether the module is up to date (exit 1 if not)

It needs rsvg-convert (Homebrew's librsvg) and nothing else: the PNG it writes is read here, without Pillow.
"""

import argparse
import hashlib
import shutil
import struct
import subprocess
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from metarmap.visualizers.visualizer import ICONS  # noqa: E402
from metarmap.web.icons import ATTRS, SHAPES, SOLID  # noqa: E402

SIZE = 20  # pixels a side, what the Copilot draws them at
OUT = ROOT / "src" / "metarmap" / "web" / "icon_masks.py"
RSVG = "/usr/local/bin/rsvg-convert"

# A mask is one shape: the icons that rely on color take their one-color version. Rainbow's three colored arcs
# become three plain arcs (SOLID["rainbow"]), so the mask has no colors: a client draws it in one. Chase keeps its
# fading dots (SHAPES), whose opacity becomes the mask's alpha
ONE_COLOR = ("rainbow",)


def shape(name: str) -> str:
    return SOLID[name] if name in ONE_COLOR else SHAPES[name]


def svg(name: str) -> str:
    """The icon in white on nothing, SIZE pixels a side (the shapes are drawn on a 24x24 viewBox, as on the web)."""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" color="#ffffff" {ATTRS}>'
        f"{shape(name)}</svg>"
    )


def rsvg() -> str:
    found = RSVG if Path(RSVG).exists() else shutil.which("rsvg-convert")
    if not found:
        raise SystemExit("rsvg-convert not found (brew install librsvg)")
    return found


def read_png(data: bytes):
    """(width, height, RGBA bytes) of an 8-bit, non-interlaced RGBA PNG (what rsvg-convert writes)."""
    pos, idat, w, h = 8, b"", 0, 0
    while pos < len(data):
        (n,) = struct.unpack(">I", data[pos : pos + 4])
        kind, body = data[pos + 4 : pos + 8], data[pos + 8 : pos + 8 + n]
        if kind == b"IHDR":
            w, h, depth, color = struct.unpack(">IIBB", body[:10])
            if (depth, color) != (8, 6) or body[12] != 0:
                raise SystemExit("expected an 8-bit RGBA, non-interlaced PNG")
        elif kind == b"IDAT":
            idat += body
        pos += 12 + n
    raw, bpp, stride = zlib.decompress(idat), 4, w * 4
    out, prev = bytearray(), bytearray(stride)
    for y in range(h):
        f, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1 : (y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b, c = prev[i], prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        out += line
        prev = line
    return w, h, bytes(out)


def render(source: str, tool: str = "") -> bytes:
    """An SVG's alpha channel at SIZE x SIZE: SIZE * SIZE bytes, row by row, 0 clear to 255 solid."""
    png = subprocess.run(
        [tool or rsvg(), "-w", str(SIZE), "-h", str(SIZE)],
        input=source.encode(),
        check=True,
        capture_output=True,
    ).stdout
    w, h, rgba = read_png(png)
    if (w, h) != (SIZE, SIZE):
        raise SystemExit(f"rsvg-convert drew {w}x{h}, not {SIZE}x{SIZE}")
    return rgba[3::4]


def mask(name: str, tool: str = "") -> bytes:
    return render(svg(name), tool)


def rev(data: bytes) -> str:
    """What a mask is known by (its ETag): it changes when the mask does."""
    return hashlib.sha1(data).hexdigest()[:8]


def module(masks: dict) -> str:
    lines = [
        '"""',
        "Generated by tools/make_icon_masks.py. Don't edit: change metarmap.web.icons.SHAPES and run the tool again.",
        "",
        f"Each visualizer icon as a {SIZE}x{SIZE} alpha mask ({SIZE * SIZE} bytes, row by row from the top left,",
        "0 clear to 255 solid; one hex string per row), and REV, what each is known by (the start of its SHA-1).",
        '"""',
        "",
        f"SIZE = {SIZE}",
        "",
        "MASKS = {",
    ]
    for name in sorted(masks):
        data = masks[name]
        lines.append(f'    "{name}": bytes.fromhex(')
        lines += [f'        "{data[y * SIZE : (y + 1) * SIZE].hex()}"' for y in range(SIZE)]
        lines.append("    ),")
    lines += ["}", "", "REV = {"]
    lines += [f'    "{name}": "{rev(masks[name])}",' for name in sorted(masks)]
    lines += ["}", ""]
    return "\n".join(lines)


def ascii_art(data: bytes) -> str:
    """A mask as text, two characters a pixel: blank clear, then lighter to solider."""
    marks = " .:+#"
    rows = []
    for y in range(SIZE):
        row = data[y * SIZE : (y + 1) * SIZE]
        levels = (0 if a == 0 else min(len(marks) - 1, 1 + a * (len(marks) - 1) // 256) for a in row)
        rows.append("".join(marks[level] * 2 for level in levels))
    return "\n".join(rows)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--preview", action="store_true", help="print each mask as ASCII art")
    parser.add_argument("--check", action="store_true", help="don't write: exit 1 if icon_masks.py is out of date")
    args = parser.parse_args(argv)

    assert set(SHAPES) == set(ICONS), "every visualizer icon needs a shape"
    tool = rsvg()
    masks = {name: mask(name, tool) for name in sorted(ICONS)}
    if args.preview:
        for name in sorted(masks):
            lit = sum(1 for a in masks[name] if a)
            print(f"{name} (rev {rev(masks[name])}, {lit} of {SIZE * SIZE} pixels drawn)")
            print("+" + "-" * (SIZE * 2) + "+")
            print("\n".join(f"|{row}|" for row in ascii_art(masks[name]).split("\n")))
            print("+" + "-" * (SIZE * 2) + "+\n")
    text = module(masks)
    current = OUT.read_text() if OUT.exists() else ""
    if args.check:
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/make_icon_masks.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    if current != text:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)} ({len(masks)} masks)")
    else:
        print(f"{OUT.relative_to(ROOT)} unchanged ({len(masks)} masks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
